def word_as_number(word: str) -> int | None:
    word_normalized = word.strip().lower()
    for candidate in (
            word_normalized,
            word_normalized.replace(" ", "-"),
            word_normalized.replace(" ", ""),
    ):
        number = _ENGLISH_NUMBERS.get(candidate)
        if number is None:
            number = _GERMAN_NUMBERS.get(candidate)
        if number is not None:
            return number
    return None

